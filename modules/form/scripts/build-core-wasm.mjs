import { spawnSync } from 'node:child_process';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const projectRoot = resolve(import.meta.dirname, '..');
const manifest = resolve(projectRoot, 'wasm/a3s-form-core-wasm/Cargo.toml');
const build = spawnSync(
  'cargo',
  ['build', '--manifest-path', manifest, '--target', 'wasm32-unknown-unknown', '--release'],
  { cwd: projectRoot, encoding: 'utf8', stdio: 'pipe' },
);

if (build.status !== 0) {
  process.stderr.write(build.stderr || build.stdout || 'Form Core WASM build failed.\n');
  process.exit(build.status ?? 1);
}

const source = resolve(
  projectRoot,
  'wasm/a3s-form-core-wasm/target/wasm32-unknown-unknown/release/a3s_form_core_wasm.wasm',
);
const output = resolve(projectRoot, 'src/wasm/form-core.wasm');
await mkdir(dirname(output), { recursive: true });
await copyFile(source, output);
const binary = await readFile(output);
const typescriptOutput = resolve(projectRoot, 'src/wasm/form-core-binary.ts');
await writeFile(
  typescriptOutput,
  `// Generated by scripts/build-core-wasm.mjs. Do not edit by hand.\nexport const FORM_CORE_WASM_BASE64: string = '${binary.toString('base64')}';\n`,
);
console.log(`Built portable Form Core WASM (${binary.length} bytes).`);
